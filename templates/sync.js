#!/usr/bin/env node
'use strict';
/**
 * templates/ is the single source of truth for app templates.
 *   node templates/sync.js
 * Regenerates:
 *   - templates/<name>/design.ar.json + design.en.json   (ready-to-render designs)
 *   - templates/<name>/README.md
 *   - web/lib/templates.json                            (Next.js builder)
 *   - app/lib/models/templates_data.dart                (Flutter builder)
 * Run it after editing any template.json.
 */
const fs = require('fs');
const path = require('path');

const root = __dirname;
const names = JSON.parse(fs.readFileSync(path.join(root, 'index.json'), 'utf8'));
const all = names.map((n) => JSON.parse(fs.readFileSync(path.join(root, n, 'template.json'), 'utf8')));

const isDark = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return 0.299 * ((n >> 16) & 255) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255) < 140;
};

function design(t, lang) {
  const cats = t.categories[lang];
  return {
    id: `template-${t.folder}-${lang}`,
    name: t.title[lang],
    type: t.type,
    tagline: lang === 'ar' ? `أهلاً بك في ${t.title.ar}` : `Welcome to ${t.title.en}`,
    colors: { ...t.colors, text: isDark(t.colors.background) ? '#FFFFFF' : '#111111' },
    font: lang === 'ar' ? 'Cairo' : 'Inter',
    logoEmoji: t.emoji,
    heroImage: '',
    language: lang,
    currency: lang === 'ar' ? 'BHD' : 'USD',
    sections: t.sections,
    categories: cats,
    products: t.products.map((p, i) => ({ id: `p${i}`, name: p.name[lang], price: p.price, category: cats[Math.min(p.category, cats.length - 1)], emoji: p.emoji, image: '', description: '' })),
    contact: { whatsapp: '', instagram: '', phone: '', address: '', email: '' },
    domain: '',
    status: 'draft',
    pages: ['home', 'products', 'cart', 'booking', 'contact'],
  };
}

for (const t of all) {
  const dir = path.join(root, t.folder);
  for (const lang of ['ar', 'en']) fs.writeFileSync(path.join(dir, `design.${lang}.json`), JSON.stringify(design(t, lang), null, 2) + '\n');
  fs.writeFileSync(path.join(dir, 'README.md'), `# ${t.emoji} ${t.title.en} — ${t.title.ar}

Template used by the KAkAo builder when a user asks for: ${t.keywords.slice(0, 8).join(', ')}.

**Screens:** ${t.screens.join(' • ')}

| File | Purpose |
|---|---|
| \`template.json\` | Source: colors, sections, categories and products in Arabic + English. Edit this. |
| \`design.ar.json\` / \`design.en.json\` | Ready designs (generated by \`node templates/sync.js\`). Drop one into \`templates/_flutter-app/assets/design.json\` to build a standalone APK. |

Colors: primary \`${t.colors.primary}\`, accent \`${t.colors.secondary}\`, background \`${t.colors.background}\`.
`);
}

// Web
const flat = all.map((t) => ({
  type: t.type, emoji: t.emoji, title: t.title, keywords: t.keywords,
  colors: [t.colors.primary, t.colors.secondary, t.colors.background],
  sections: t.sections, categories: t.categories,
  products: t.products.map((p) => [p.name.ar, p.name.en, p.price, p.emoji, p.category]),
}));
fs.writeFileSync(path.join(root, '..', 'web', 'lib', 'templates.json'), JSON.stringify(flat, null, 1) + '\n');

// Flutter
const dart = (v) => JSON.stringify(v).replace(/\$/g, '\\$');
const lines = all.map((t) => `  {
    'type': ${dart(t.type)},
    'emoji': ${dart(t.emoji)},
    'title': {'ar': ${dart(t.title.ar)}, 'en': ${dart(t.title.en)}},
    'keywords': <String>[${t.keywords.map(dart).join(', ')}],
    'primary': ${dart(t.colors.primary)},
    'secondary': ${dart(t.colors.secondary)},
    'background': ${dart(t.colors.background)},
    'sections': <String>[${t.sections.map(dart).join(', ')}],
    'categories': {'ar': <String>[${t.categories.ar.map(dart).join(', ')}], 'en': <String>[${t.categories.en.map(dart).join(', ')}]},
    'products': <Map<String, Object>>[
${t.products.map((p) => `      {'ar': ${dart(p.name.ar)}, 'en': ${dart(p.name.en)}, 'price': ${p.price}, 'emoji': ${dart(p.emoji)}, 'cat': ${p.category}},`).join('\n')}
    ],
  },`).join('\n');
fs.writeFileSync(path.join(root, '..', 'app', 'lib', 'models', 'templates_data.dart'), `// GENERATED by templates/sync.js — do not edit. Edit templates/<name>/template.json instead.
// ignore_for_file: prefer_single_quotes

const templatesData = <Map<String, Object>>[
${lines}
];
`);
console.log(`synced ${all.length} templates`);
